// Package eval: оценочные функции. Оценка всегда с точки зрения того, чей ход (negamax).
package eval

import (
	"quoridor/board"
	"quoridor/path"
)

// V1: гонка путей + стены в запасе + право хода (этап 5).
//
//	100 за каждый шаг преимущества в пути, 140 за стену в запасе, 20 за право хода.
//
// Вес стены подобран матчами против Walker: при 10–40 глубокий поиск тратит все стены
// и от страха перед стенами соперника топчется на месте (проигрывает «ходоку»),
// при 120–250 бот стабильно выигрывает на любой глубине 3–6. Точный вес потом уточнит SPSA.
func V1(b *board.Board) int {
	me := int(b.Turn)
	dMe, dOp := path.Len(b, me), path.Len(b, 1-me)
	return 100*(dOp-dMe) + 140*(int(b.Walls[me])-int(b.Walls[1-me])) + 20
}

